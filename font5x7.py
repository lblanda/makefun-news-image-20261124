# Width of one glyph cell in pixels at scale 1 (5 glyph columns + 1 gap).
CHAR_W = 6
CHAR_H = 7


def text_width(text, scale=1):
    """Pixel width of text at the given scale (upper-cased first)."""
    return len(text.upper()) * CHAR_W * scale


def draw_text(canvas, x, y, text, color, scale=1):
    """Draw upper-cased text on canvas at (x, y); returns the x after it.

    canvas is a Canvas object (see main.py) exposing set_pixel().
    Characters with no glyph fall back to a blank cell so a stray
    character can never crash the render.
    """
    text = text.upper()
    cx = x
    for ch in text:
        glyph = GLYPHS.get(ch, GLYPHS[" "])
        for row in range(7):
            bits = glyph[row]
            for col in range(5):
                if bits & (0x10 >> col):
                    for dy in range(scale):
                        for dx in range(scale):
                            canvas.set_pixel(cx + col * scale + dx,
                                             y + row * scale + dy, color)
        cx += CHAR_W * scale
    return cx


def wrap_text(text, max_chars):
    """Greedy word wrap; returns a list of lines, each <= max_chars."""
    words = text.split(" ")
    lines = []
    current = ""
    for word in words:
        if not current:
            current = word
        elif len(current) + 1 + len(word) <= max_chars:
            current += " " + word
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines
